    def _extract_number(self, text: str, context_word: str) -> int | None:
        # Look for numbers near the context word
        patterns = [
            rf"(\d[\d,]*)\s*(?:rs\.?|₹)?\s*{context_word}",
            rf"{context_word}\s*(?:rs\.?|₹)?\s*(\d[\d,]*)",
            rf"(?:rs\.?|₹)\s*(\d[\d,]*)",
            rf"(\d+)\s*{context_word}",
            rf"under\s*(?:rs\.?|₹)?\s*(\d[\d,]*)",
        ]
        for pattern in patterns:
            match = re.search(pattern, text)
            if match:
                return int(match.group(1).replace(",", ""))
        # Generic number extraction
        numbers = re.findall(r"\d[\d,]*", text)
        for n in numbers:
            val = int(n.replace(",", ""))
            if context_word == "budget" and val >= 1000:
                return val
            elif context_word == "day" and 1 <= val <= 30:
                return val
            elif context_word == "people" and 1 <= val <= 20:
                return val
        return None

